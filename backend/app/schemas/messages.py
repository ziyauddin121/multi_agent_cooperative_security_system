"""
MACSS — Inter-Agent Message Schema
===================================
All messages exchanged between agents through the Redis blackboard
MUST conform to these Pydantic schemas.

Every field is typed and validated before being published.
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, Field, field_validator


# ═══════════════════════════════════════════════════════════════
# Enumerations — every enum value used in messages is defined here
# ═══════════════════════════════════════════════════════════════

class Severity(str, Enum):
    """Threat severity levels (LOW → CRITICAL)."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class MessageType(str, Enum):
    """What kind of message an agent is publishing."""
    ALERT = "ALERT"               # An agent detected something
    EVIDENCE = "EVIDENCE"         # Forensics gathered corroborating evidence
    DECISION = "DECISION"         # Coordinator's final ruling
    ACTION = "ACTION"             # A containment action was triggered
    VERIFICATION = "VERIFICATION" # Result of post-action verification
    HEARTBEAT = "HEARTBEAT"       # Agent liveness ping
    STATUS_UPDATE = "STATUS_UPDATE"


class EventType(str, Enum):
    """Types of raw sensor events generated by the simulator."""
    # DDoS events
    HIGH_TRAFFIC_RATE = "HIGH_TRAFFIC_RATE"
    CONNECTION_FLOOD = "CONNECTION_FLOOD"
    SCAN_DETECTED = "SCAN_DETECTED"
    DDOS_SUSPECTED = "DDOS_SUSPECTED"

    # Ransomware / Endpoint events
    FILE_MODIFICATION_SPIKE = "FILE_MODIFICATION_SPIKE"
    FILE_RENAME_SPIKE = "FILE_RENAME_SPIKE"
    MASS_FILE_ACCESS = "MASS_FILE_ACCESS"
    SUSPICIOUS_PROCESS = "SUSPICIOUS_PROCESS"
    CPU_SPIKE = "CPU_SPIKE"
    RANSOMWARE_SUSPECTED = "RANSOMWARE_SUSPECTED"

    # Lateral movement events
    UNUSUAL_AUTH = "UNUSUAL_AUTH"
    NEW_REMOTE_CONNECTION = "NEW_REMOTE_CONNECTION"
    LATERAL_MOVEMENT_SUSPECTED = "LATERAL_MOVEMENT_SUSPECTED"
    PRIVILEGE_ESCALATION = "PRIVILEGE_ESCALATION"

    # Generic / meta
    NORMAL_TRAFFIC = "NORMAL_TRAFFIC"
    SIMULATION_START = "SIMULATION_START"
    SIMULATION_STOP = "SIMULATION_STOP"
    PHASE_CHANGE = "PHASE_CHANGE"


class ActionType(str, Enum):
    """Safe simulated containment actions."""
    RATE_LIMIT = "RATE_LIMIT"
    BLOCK_SOURCE = "BLOCK_SOURCE"
    ISOLATE_ENDPOINT = "ISOLATE_ENDPOINT"
    BLOCK_CONNECTION = "BLOCK_CONNECTION"
    QUARANTINE_HOST = "QUARANTINE_HOST"
    NOTIFY_ADMIN = "NOTIFY_ADMIN"
    NO_ACTION = "NO_ACTION"
    INVESTIGATE = "INVESTIGATE"


class VerificationResult(str, Enum):
    """Outcome after a containment action is verified."""
    SUCCESS = "SUCCESS"
    PARTIAL_SUCCESS = "PARTIAL_SUCCESS"
    FAILED = "FAILED"
    PENDING = "PENDING"


class IncidentStatus(str, Enum):
    """Lifecycle state of an incident."""
    OPEN = "OPEN"
    INVESTIGATING = "INVESTIGATING"
    CONTAINED = "CONTAINED"
    RESOLVED = "RESOLVED"
    FALSE_POSITIVE = "FALSE_POSITIVE"


class AgentId(str, Enum):
    """Known agent identifiers."""
    PERIMETER = "perimeter-agent"
    ENDPOINT = "endpoint-agent"
    FORENSICS = "forensics-agent"
    COORDINATOR = "coordinator-agent"
    BASELINE = "baseline-agent"
    SIMULATOR = "simulator"


# ═══════════════════════════════════════════════════════════════
# Helper — generate IDs
# ═══════════════════════════════════════════════════════════════

def new_id(prefix: str = "id") -> str:
    """Generate a short prefixed UUID, e.g. 'evt-3f2a…'"""
    return f"{prefix}-{uuid.uuid4().hex[:8]}"


def now_utc() -> datetime:
    return datetime.now(timezone.utc)


# ═══════════════════════════════════════════════════════════════
# Base — all messages inherit from this
# ═══════════════════════════════════════════════════════════════

class BaseMessage(BaseModel):
    """
    Root schema for every message on the Redis blackboard.
    Agents MUST validate against this before publishing.
    """
    message_id: str = Field(default_factory=lambda: new_id("msg"))
    event_id: str = Field(default_factory=lambda: new_id("evt"))
    timestamp: datetime = Field(default_factory=now_utc)
    agent_id: str                                  # who published this
    message_type: MessageType
    correlation_id: Optional[str] = None           # links related messages
    tags: list[str] = Field(default_factory=list)

    @field_validator("timestamp", mode="before")
    @classmethod
    def ensure_utc(cls, v):
        if isinstance(v, str):
            return datetime.fromisoformat(v)
        return v

    def to_redis_dict(self) -> dict[str, str]:
        """Serialize to a flat string dict suitable for Redis XADD."""
        import orjson
        data = self.model_dump(mode="json")
        return {k: orjson.dumps(v).decode() if not isinstance(v, str) else v
                for k, v in data.items()}

    @classmethod
    def from_redis_dict(cls, data: dict[str, bytes | str]):
        """Deserialize from Redis stream entry."""
        import orjson
        parsed = {}
        for k, v in data.items():
            key = k.decode() if isinstance(k, bytes) else k
            val = v.decode() if isinstance(v, bytes) else v
            try:
                parsed[key] = orjson.loads(val)
            except Exception:
                parsed[key] = val
        return cls(**parsed)


# ═══════════════════════════════════════════════════════════════
# Alert Message — published by Perimeter, Endpoint agents
# ═══════════════════════════════════════════════════════════════

class AlertMessage(BaseMessage):
    """
    An agent detected a potential threat and is publishing an alert.
    Example: Perimeter Agent detects DDoS-like traffic spike.
    """
    message_type: MessageType = MessageType.ALERT
    incident_id: Optional[str] = None
    event_type: EventType
    severity: Severity
    confidence: float = Field(ge=0.0, le=1.0)
    source: str                  # source host / IP
    target: str                  # target service / host
    evidence: dict[str, Any] = Field(default_factory=dict)
    recommended_action: ActionType = ActionType.INVESTIGATE
    affected_hosts: list[str] = Field(default_factory=list)

    @field_validator("confidence")
    @classmethod
    def confidence_range(cls, v: float) -> float:
        return round(v, 4)


# ═══════════════════════════════════════════════════════════════
# Evidence Message — published by Forensics Agent
# ═══════════════════════════════════════════════════════════════

class EvidenceMessage(BaseMessage):
    """
    Forensics agent correlates alerts and publishes a corroborated
    evidence package for the Coordinator to consume.
    """
    message_type: MessageType = MessageType.EVIDENCE
    incident_id: str
    attack_type: EventType
    severity: Severity
    confidence: float = Field(ge=0.0, le=1.0)
    affected_hosts: list[str]
    evidence_count: int = 0
    correlated_alert_ids: list[str] = Field(default_factory=list)
    timeline: list[dict[str, Any]] = Field(default_factory=list)
    recommended_action: ActionType = ActionType.INVESTIGATE
    evidence: dict[str, Any] = Field(default_factory=dict)


# ═══════════════════════════════════════════════════════════════
# Decision Message — published by Coordinator Agent
# ═══════════════════════════════════════════════════════════════

class ConflictEntry(BaseModel):
    """Represents one agent's recommendation in a conflict."""
    agent_id: str
    recommended_action: ActionType
    severity: Severity
    confidence: float
    weight: float = 0.0   # computed during resolution


class DecisionMessage(BaseMessage):
    """
    Coordinator's final ruling after conflict resolution.
    Contains the winning action, reasoning, and all conflicting views.
    """
    message_type: MessageType = MessageType.DECISION
    incident_id: str
    selected_action: ActionType
    severity: Severity
    confidence: float = Field(ge=0.0, le=1.0)
    reason: str                                     # human-readable explanation
    conflicting_recommendations: list[ConflictEntry] = Field(default_factory=list)
    affected_hosts: list[str] = Field(default_factory=list)
    is_multi_agent: bool = True                     # False for baseline


# ═══════════════════════════════════════════════════════════════
# Action Message — published after containment is triggered
# ═══════════════════════════════════════════════════════════════

class ActionMessage(BaseMessage):
    """
    Records that a containment action was executed (simulated).
    Safe simulation only — no destructive OS/network commands.
    """
    message_type: MessageType = MessageType.ACTION
    decision_id: str
    incident_id: str
    action_type: ActionType
    target_host: str
    action_status: str = "EXECUTED"    # EXECUTED | PENDING | FAILED
    simulation_note: str = ""          # explains what was simulated


# ═══════════════════════════════════════════════════════════════
# Verification Message — result after verifying containment
# ═══════════════════════════════════════════════════════════════

class VerificationMessage(BaseMessage):
    """
    Result of the post-action verification step.
    Checks whether the threat is still present after containment.
    """
    message_type: MessageType = MessageType.VERIFICATION
    action_id: str
    incident_id: str
    result: VerificationResult
    checks: dict[str, bool] = Field(default_factory=dict)
    notes: str = ""


# ═══════════════════════════════════════════════════════════════
# Heartbeat Message — agent liveness
# ═══════════════════════════════════════════════════════════════

class HeartbeatMessage(BaseMessage):
    """
    Periodic liveness ping from each agent.
    Coordinator monitors these to detect dead agents.
    """
    message_type: MessageType = MessageType.HEARTBEAT
    status: str = "running"
    alerts_published: int = 0
    uptime_seconds: float = 0.0
    extra: dict[str, Any] = Field(default_factory=dict)


# ═══════════════════════════════════════════════════════════════
# Raw Sensor Event — generated by the Attack Simulator
# ═══════════════════════════════════════════════════════════════

class SensorEvent(BaseModel):
    """
    A raw simulated sensor/telemetry event published by the simulator
    to the security:events stream. Agents consume and analyse these.
    """
    event_id: str = Field(default_factory=lambda: new_id("evt"))
    timestamp: datetime = Field(default_factory=now_utc)
    event_type: EventType
    source: str
    target: str
    payload: dict[str, Any] = Field(default_factory=dict)
    simulation_phase: str = "unknown"
    experiment_id: Optional[str] = None
    is_attack: bool = True    # False for baseline/normal events

    def to_redis_dict(self) -> dict[str, str]:
        import orjson
        data = self.model_dump(mode="json")
        return {k: orjson.dumps(v).decode() if not isinstance(v, str) else v
                for k, v in data.items()}

    @classmethod
    def from_redis_dict(cls, data: dict[str, bytes | str]):
        import orjson
        parsed = {}
        for k, v in data.items():
            key = k.decode() if isinstance(k, bytes) else k
            val = v.decode() if isinstance(v, bytes) else v
            try:
                parsed[key] = orjson.loads(val)
            except Exception:
                parsed[key] = val
        return cls(**parsed)


# ═══════════════════════════════════════════════════════════════
# Experiment Config Schema
# ═══════════════════════════════════════════════════════════════

class ExperimentConfig(BaseModel):
    """Configuration for a reproducible experiment run."""
    experiment_id: str = Field(default_factory=lambda: new_id("exp"))
    name: str
    scenario: str               # "ddos" | "ransomware" | "lateral" | "combined"
    attack_intensity: str       # "low" | "medium" | "high"
    number_of_hosts: int = 4
    random_seed: int = 42
    is_multi_agent: bool = True
    duration_seconds: int = 60
    extra_config: dict[str, Any] = Field(default_factory=dict)
